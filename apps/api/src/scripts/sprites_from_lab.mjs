// Writes src/sprites.ts from the mascot's layers in the screen lab: the sprites "mascot/cat/*" in
// screen-lab/sprites.js (one row of text per row of pixels, "#" = lit). Run after the art changes:
//   node apps/api/src/scripts/sprites_from_lab.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const at = p => fileURLToPath(new URL(p, import.meta.url));
const src = readFileSync(at("../../../../screen-lab/sprites.js"), "utf8");
const sprites = {};
for (const m of src.matchAll(/sprite\("(mascot\/cat\/[^"]+)",\s*`([^`]*)`/g)) {
  const rows = m[2].split("\n").map(r => r.trim()).filter(Boolean);
  const w = Math.max(...rows.map(r => r.length));
  if (rows.some(r => r.length !== w)) throw new Error(`${m[1]}: every row must be ${w} characters`);
  sprites[m[1]] = { w, h: rows.length, rows };
}
const names = Object.keys(sprites);
if (!names.length) throw new Error("no mascot/cat/* sprites found in screen-lab/sprites.js");
const body = names.map(n => `  "${n}": { w: ${sprites[n].w}, h: ${sprites[n].h}, rows: [\n${sprites[n].rows.map(r => `    "${r}",`).join("\n")}\n  ] },`).join("\n");
writeFileSync(at("../sprites.ts"), `// The mascot as pixel art: one string per row, "#" is a lit pixel. Generated by src/scripts/sprites_from_lab.mjs
// from the sprites "mascot/cat/*" in screen-lab/sprites.js: edit the art there, then run the script.
export const SPRITES = {
${body}
} as const;
export type SpriteName = keyof typeof SPRITES;
`);
console.log(`wrote src/sprites.ts: ${names.join(", ")}`);
