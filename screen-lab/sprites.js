// ---- The mascot, from the designer's pencil sketches: a box for a head with a face in it.
// "cat" is the mascot. The others are earlier sketches, kept to compare ("Mascot face" on the page):
//   cat     box with two cat ears, round eyes joined by a bar, square mouth
//   round   round eyes, wide flat mouth
//   odd     one big eye, one small eye, triangle mouth
//   tall    tall rounded eyes with a band across the top, small square mouth
// Each face is six layers drawn on one grid, like sheets of tracing paper:
//   mascot/NAME/head   the box (and ears): always lit
//   mascot/NAME/eyes   eyes open           mascot/NAME/blink  eyes shut
//   mascot/NAME/quiet  mouth when quiet    mascot/NAME/half   mouth for soft sound    mascot/NAME/open  mouth for loud sound
// The six layers of one face must be the same size so the parts stay lined up ("cat" is 26 wide and
// 21 tall, the others 26 wide and 20 tall). A new face is six more layers under a new NAME; it then
// shows up in the menu by itself. A name with "/" in it is a part: it is left out of the Avatar menu.

