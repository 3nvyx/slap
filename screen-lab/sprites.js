// ---- The mascot, from the designer's pencil sketches: a box for a head with a face in it.
// There are several faces to choose from ("Mascot face" on the page):
//   round   round eyes, wide flat mouth
//   odd     one big eye, one small eye, triangle mouth
//   tall    tall rounded eyes with a band across the top, small square mouth
// Everything is drawn in layers on one grid (26 wide, 20 tall), like sheets of tracing paper.
// "mascot/head" is the box. Each face has five layers, with "#" only inside the box:
//   mascot/NAME/eyes   eyes open           mascot/NAME/blink  eyes shut
//   mascot/NAME/quiet  mouth when quiet    mascot/NAME/half   mouth for soft sound    mascot/NAME/open  mouth for loud sound
// A new face is five more layers under a new NAME; it then shows up in the menu by itself.
// Keep every layer the same size so the parts stay lined up.
// A name with "/" in it is a part: it is left out of the Avatar menu.

