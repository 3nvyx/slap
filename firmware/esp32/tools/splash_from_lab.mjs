// Writes src/splash.h from the switch-on art in the screen lab (the sprite "screen/splash" in
// screen-lab/sprites.js: 64 rows of 128 characters, "#" = lit). Run after the art changes:
//   node firmware/esp32/tools/splash_from_lab.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const at = p => fileURLToPath(new URL(p, import.meta.url));
const src = readFileSync(at("../../../screen-lab/sprites.js"), "utf8");
const m = /sprite\("screen\/splash",\s*`([^`]*)`/.exec(src);
if (!m) throw new Error('sprite "screen/splash" not found in screen-lab/sprites.js');
const rows = m[1].split("\n").map(r => r.trim()).filter(Boolean);
if (rows.length !== 64 || rows.some(r => r.length !== 128)) throw new Error("the art must be 64 rows of 128 characters");
const bytes = new Uint8Array(1024);
rows.forEach((r, y) => [...r].forEach((c, x) => { if (c !== "." && c !== " ") bytes[y * 16 + (x >> 3)] |= 1 << (x & 7); }));
const lines = [];
for (let i = 0; i < 1024; i += 16) lines.push("  " + [...bytes.subarray(i, i + 16)].map(b => "0x" + b.toString(16).padStart(2, "0")).join(", ") + ",");
writeFileSync(at("../src/splash.h"), `// Switch-on art, 128 x 64, XBM layout (16 bytes per row, LSB = leftmost pixel, 1 = lit).
// Generated by tools/splash_from_lab.mjs from the sprite "screen/splash" in screen-lab/sprites.js: edit the art there.
#pragma once
#include <stdint.h>

const uint8_t kSplash[1024] = {
${lines.join("\n")}
};
`);
console.log("wrote src/splash.h");
