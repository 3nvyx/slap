// Writes src/splash.h from the switch-on animation in the screen lab: the sprites "screen/splash/1", "/2", ...
// in screen-lab/sprites.js (64 rows of 128 characters each, "#" = lit) and SPLASH_FRAME_MS (how long each frame
// but the last is shown). Run after the art changes:
//   node firmware/esp32/tools/splash_from_lab.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const at = p => fileURLToPath(new URL(p, import.meta.url));
const src = readFileSync(at("../../../screen-lab/sprites.js"), "utf8");
const ms = JSON.parse(/const SPLASH_FRAME_MS = (\[[^\]]*\]);/.exec(src)?.[1] ?? "null");
if (!Array.isArray(ms)) throw new Error("SPLASH_FRAME_MS not found in screen-lab/sprites.js");
const frames = [];
for (let n = 1; ; n++) {
  const m = new RegExp(`sprite\\("screen/splash/${n}",\\s*\`([^\`]*)\``).exec(src);
  if (!m) break;
  const rows = m[1].split("\n").map(r => r.trim()).filter(Boolean);
  if (rows.length !== 64 || rows.some(r => r.length !== 128)) throw new Error(`screen/splash/${n} must be 64 rows of 128 characters`);
  const bytes = new Uint8Array(1024);
  rows.forEach((r, y) => [...r].forEach((c, x) => { if (c !== "." && c !== " ") bytes[y * 16 + (x >> 3)] |= 1 << (x & 7); }));
  frames.push(bytes);
}
if (frames.length !== ms.length + 1) throw new Error(`${frames.length} frames need ${frames.length - 1} times in SPLASH_FRAME_MS, found ${ms.length}`);
const body = frames.map((bytes, i) => {
  const lines = [];
  for (let k = 0; k < 1024; k += 16) lines.push("    " + [...bytes.subarray(k, k + 16)].map(b => "0x" + b.toString(16).padStart(2, "0")).join(", ") + ",");
  return `  {   // frame ${i + 1}\n${lines.join("\n")}\n  },`;
}).join("\n");
writeFileSync(at("../src/splash.h"), `// Switch-on animation: ${frames.length} frames of 128 x 64, XBM layout (16 bytes per row, LSB = leftmost pixel, 1 = lit).
// Generated by tools/splash_from_lab.mjs from the sprites "screen/splash/N" in screen-lab/sprites.js: edit the art there.
#pragma once
#include <stdint.h>

constexpr int kSplashFrames = ${frames.length};
// How long each frame but the last is shown, in ms; the last one stays until the splash ends.
const uint16_t kSplashFrameMs[kSplashFrames - 1] = { ${ms.join(", ")} };

const uint8_t kSplash[kSplashFrames][1024] = {
${body}
};
`);
console.log(`wrote src/splash.h: ${frames.length} frames, ${ms.reduce((a, b) => a + b, 0)} ms before the last`);
